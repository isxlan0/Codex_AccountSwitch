// Run with Node.js 24+: node tools/sync_ccs_presets.mjs
// Uses only the checked-out reference; no network or package dependencies.
import { readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import { fileURLToPath } from "node:url";

const sourceUrl = new URL("../.pb/cc-switch/src/config/codexProviderPresets.ts", import.meta.url);
const outputUrl = new URL("../webui/js/ccs-provider-presets.js", import.meta.url);
const source = readFileSync(sourceUrl, "utf8");
// All imports in this module are type-only in use. Node strips explicit type
// imports; remove the remaining ProviderCategory import (used only in a type).
const executable = stripTypeScriptTypes(source, { mode: "strip" })
  .replace(/^import \{ ProviderCategory \} from "\.\.\/types";\s*$/m, "");
const { codexProviderPresets } = await import(
  `data:text/javascript;base64,${Buffer.from(executable).toString("base64")}`
);
const templateUrl = new URL("../.pb/cc-switch/src/config/codexTemplates.ts", import.meta.url);
const templateExecutable = stripTypeScriptTypes(readFileSync(templateUrl, "utf8"), { mode: "strip" });
const { getCodexCustomTemplate } = await import(
  `data:text/javascript;base64,${Buffer.from(templateExecutable).toString("base64")}`
);
const customTemplate = getCodexCustomTemplate();

// The templates use JSON-quoted TOML strings. Read only exact assignment keys;
// missing values remain empty, including the official OAuth configuration.
function configString(config, key) {
  const assignment = config.match(new RegExp(`^${key}\\s*=\\s*("(?:[^"\\\\]|\\\\.)*")\\s*$`, "m"));
  return assignment ? JSON.parse(assignment[1]) : "";
}

const presets = codexProviderPresets.map((preset, index) => ({
  ...preset,
  // Preserve CCS's original array-index IDs, including hidden entries.
  id: `codex-${index}`,
  baseUrl: configString(preset.config, "base_url"),
  model: configString(preset.config, "model"),
  category: preset.category ?? "",
  icon: preset.icon ?? "",
  color: preset.iconColor ?? "",
  settingsConfig: { auth: preset.auth, config: preset.config },
  // The Codex presets do not contain these fields; do not invent scripts/text.
  usageScript: null,
  description: "",
}));

const header = `// Generated by tools/sync_ccs_presets.mjs; do not edit by hand.\n` +
  `// Source: .pb/cc-switch/src/config/codexProviderPresets.ts\n` +
  `// Custom template: .pb/cc-switch/src/config/codexTemplates.ts\n` +
  `// Includes hidden entries and OAuth metadata exactly as in the reference.\n`;
writeFileSync(outputUrl,
  `${header}window.CCS_CODEX_PRESETS = ${JSON.stringify(presets, null, 2)};\n` +
  `window.CCS_CODEX_CUSTOM_TEMPLATE = ${JSON.stringify(customTemplate, null, 2)};\n`, "utf8");
console.log(`Wrote ${presets.length} Codex presets to ${fileURLToPath(outputUrl)}`);

// Match ProviderIcon.tsx: URL-backed icons take precedence over inline SVG.
// Convert the source's local asset imports to data URIs before executing its
// curated name mapping; export only names actually used by Codex presets.
const iconIndexUrl = new URL("../.pb/cc-switch/src/icons/extracted/index.ts", import.meta.url);
const mimeTypes = { png: "image/png", jpg: "image/jpeg", svg: "image/svg+xml" };
const iconSource = readFileSync(iconIndexUrl, "utf8")
  .replace(/^import (\w+) from "(\.\/[^"?]+)(?:\?url)?";$/gm, (_, binding, path) => {
    const bytes = readFileSync(new URL(path, iconIndexUrl));
    const mime = mimeTypes[path.split(".").at(-1)];
    return `const ${binding} = ${JSON.stringify(`data:${mime};base64,${bytes.toString("base64")}`)};`;
  })
  .replace(/^export \{ getIconMetadata, isTileIcon \} from "\.\/metadata";$/m, "");
const iconExecutable = stripTypeScriptTypes(iconSource, { mode: "strip" });
const { getIcon, getIconUrl, isUrlIcon } = await import(
  `data:text/javascript;base64,${Buffer.from(iconExecutable).toString("base64")}`
);
const iconNames = [...new Set(presets.map((preset) => preset.icon).filter(Boolean))];
const providerIcons = {};
const missingIcons = [];
for (const name of iconNames) {
  const resource = isUrlIcon(name) ? getIconUrl(name) : getIcon(name);
  if (resource) providerIcons[name] = resource;
  else missingIcons.push(name);
}
const iconOutputUrl = new URL("../webui/js/ccs-provider-icons.js", import.meta.url);
writeFileSync(iconOutputUrl,
  `// Generated by tools/sync_ccs_presets.mjs; do not edit by hand.\n` +
  `// Source: .pb/cc-switch/src/icons/extracted/index.ts and its local asset imports.\n` +
  `// Inline SVG strings or local data URIs; only Codex preset icon names are included.\n` +
  `window.CCS_PROVIDER_ICONS = ${JSON.stringify(providerIcons, null, 2)};\n`, "utf8");
console.log(`Wrote ${Object.keys(providerIcons).length}/${iconNames.length} Codex provider icons; missing: ${missingIcons.join(", ") || "none"}`);
